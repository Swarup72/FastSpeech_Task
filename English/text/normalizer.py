"""English text normalizer for Svarah dataset.

Provides deterministic, auditable text normalization for Indian English TTS:
- Preserves original transcripts and Indian proper nouns / loanwords.
- Normalizes whitespace, quotes, dashes, and stray characters.
- Expands currencies (₹, Rs., $, etc.) and symbols (%, &, +, @).
- Expands ordinal numbers (1st, 2nd, 3rd, 11th, etc.) and number ranges (15-17).
- Expands cardinal numbers, decimals, years, and digit-by-digit phone/ID sequences.
- Spells out initialisms (UPI -> U P I, DTH -> D T H, RSS -> R S S, etc.).
- Normalizes pronounceable acronyms (COVAXIN -> Covaxin).
- Provides both `normalize_text` and auditable `normalize_text_verbose`.
"""

from __future__ import annotations

import re
from typing import Any

import inflect

_INFLECT = inflect.engine()

# Initialisms that are spoken letter-by-letter in Indian English speech
_INITIALISMS: dict[str, str] = {
    "UPI": "U P I",
    "DTH": "D T H",
    "RSS": "R S S",
    "SBI": "S B I",
    "RBI": "R B I",
    "ATM": "A T M",
    "OTP": "O T P",
    "SMS": "S M S",
    "KYC": "K Y C",
    "PIN": "P I N",
    "PAN": "P A N",
    "PRAN": "P R A N",
    "HP": "H P",
    "TV": "T V",
    "FD": "F D",
    "RD": "R D",
    "CEO": "C E O",
    "PM": "P M",
    "CM": "C M",
    "ML": "M L",
    "AI": "A I",
    "ID": "I D",
    "UT": "U T",
    "CE": "C E",
    "BCE": "B C E",
    "AD": "A D",
    "BC": "B C",
    "WHO": "W H O",
    "FIR": "F I R",
    "GST": "G S T",
    "EPFO": "E P F O",
    "NPS": "N P S",
    "PF": "P F",
    "LIC": "L I C",
}

# Pronounceable acronyms / brands that should be title-cased rather than letter-spaced
_PRONOUNCEABLE_ACRONYMS: dict[str, str] = {
    "COVAXIN": "Covaxin",
    "COVISHIELD": "Covishield",
    "COVID": "Covid",
    "AIIMS": "Aiims",
    "ISRO": "Isro",
    "NASA": "Nasa",
    "NEET": "Neet",
    "GATE": "Gate",
    "UGC": "Ugc",
    "NCERT": "Ncert",
    "CBSE": "Cbse",
    "ICSE": "Icse",
}

# Currency mappings
_CURRENCY_SYMBOLS: list[tuple[re.Pattern[str], str]] = [
    (re.compile(r"₹\s*(\d+(?:\.\d+)?)"), r"\1 rupees"),
    (re.compile(r"(?:Rs\.?|INR)\s*(\d+(?:\.\d+)?)", re.IGNORECASE), r"\1 rupees"),
    (re.compile(r"(\d+(?:\.\d+)?)\s*(?:Rs\.?|INR)", re.IGNORECASE), r"\1 rupees"),
    (re.compile(r"\$\s*(\d+(?:\.\d+)?)"), r"\1 dollars"),
    (re.compile(r"(\d+(?:\.\d+)?)\s*dollars?", re.IGNORECASE), r"\1 dollars"),
]

# Ordinal regex: 1st, 2nd, 3rd, 4th, 11th, 21st, 100th, etc.
_ORDINAL_RE = re.compile(r"\b(\d+)(st|nd|rd|th)\b", re.IGNORECASE)

# Range regex: 15-17 or 15 - 17
_RANGE_RE = re.compile(r"\b(\d+)\s*[-–]\s*(\d+)\b")

# Plus notation: 18+ -> 18 plus
_PLUS_RE = re.compile(r"\b(\d+)\s*\+(?!\+)")


def _expand_digit_sequence(s: str) -> str:
    """Read a long digit string (phone number, account number) digit-by-digit."""
    digit_names = {
        "0": "zero",
        "1": "one",
        "2": "two",
        "3": "three",
        "4": "four",
        "5": "five",
        "6": "six",
        "7": "seven",
        "8": "eight",
        "9": "nine",
    }
    return " ".join(digit_names[d] for d in s if d in digit_names)


def _expand_number_token(num_str: str) -> str:
    """Expand a numeric string into spoken English words."""
    # Check for phone numbers or IDs (5 or more digits)
    if len(num_str) >= 5 and "." not in num_str:
        return _expand_digit_sequence(num_str)

    try:
        if "." in num_str:
            val = float(num_str)
            words = _INFLECT.number_to_words(val)
        else:
            val_int = int(num_str)
            # Four-digit years between 1000 and 2099
            if 1000 <= val_int <= 2099 and not (val_int % 100 == 0):
                words = _INFLECT.number_to_words(val_int, group=2)
            else:
                words = _INFLECT.number_to_words(val_int)
        # Remove commas generated by inflect
        words = words.replace(",", "")
        return words
    except Exception:
        return num_str


def normalize_text_verbose(text: str) -> tuple[str, list[dict[str, Any]]]:
    """Normalize English text and return auditable record of changes.

    Args:
        text: Raw transcript string.

    Returns:
        Tuple of (normalized_text, audit_log).
    """
    audit: list[dict[str, Any]] = []

    def record_change(stage: str, before: str, after: str, reason: str) -> None:
        if before != after:
            audit.append({
                "stage": stage,
                "before": before,
                "after": after,
                "reason": reason,
            })

    current = text

    # Stage 1: Clean quotes, dashes, stray symbols
    step1 = current
    # Normalize unicode quotes
    step1 = re.sub(r"[‘’`´]", "'", step1)
    step1 = re.sub(r"[“”]", '"', step1)
    # Normalize unicode dashes
    step1 = re.sub(r"[—–−]", "-", step1)
    # Remove unwanted punctuation/symbols while preserving TTS-relevant ones
    step1 = re.sub(r"[~*_#\^/\\|<>{}\[\]]", " ", step1)
    record_change("quote_dash_symbol_cleanup", current, step1, "Normalize quotes and remove stray characters")
    current = step1

    # Stage 2: Specific symbol expansions (&, %, +, @)
    step2 = current
    # & between words or J&K
    step2 = re.sub(r"J\s*&\s*K", "J and K", step2, flags=re.IGNORECASE)
    step2 = re.sub(r"\s*&\s*", " and ", step2)
    # Percentage: 100% or 40 %
    step2 = re.sub(r"(\d+(?:\.\d+)?)\s*%", r"\1 percent", step2)
    # Plus sign: 18+ -> 18 plus
    step2 = _PLUS_RE.sub(r"\1 plus", step2)
    # @ symbol: e.g. user@domain -> user at domain
    step2 = re.sub(r"\s*@\s*", " at ", step2)
    record_change("symbol_expansion", current, step2, "Expand &, %, +, @ to words")
    current = step2

    # Stage 3: Currencies
    step3 = current
    for pat, repl in _CURRENCY_SYMBOLS:
        step3 = pat.sub(repl, step3)
    record_change("currency_expansion", current, step3, "Expand currency symbols to rupees / dollars")
    current = step3

    # Stage 4: Ordinal numbers (e.g. 11th -> eleventh, 1st -> first)
    step4 = current

    def _replace_ordinal(match: re.Match[str]) -> str:
        num = int(match.group(1))
        try:
            ord_word = _INFLECT.number_to_words(_INFLECT.ordinal(num))
            return ord_word.replace(",", "")
        except Exception:
            return match.group(0)

    step4 = _ORDINAL_RE.sub(_replace_ordinal, step4)
    record_change("ordinal_expansion", current, step4, "Convert ordinals to words")
    current = step4

    # Stage 5: Number ranges (e.g. 15-17 -> 15 to 17)
    step5 = current
    step5 = _RANGE_RE.sub(r"\1 to \2", step5)
    record_change("range_expansion", current, step5, "Convert number ranges to 'to'")
    current = step5

    # Stage 6: Cardinal numbers and decimals
    step6 = current

    def _replace_number(match: re.Match[str]) -> str:
        return _expand_number_token(match.group(0))

    # Match numbers (integers or decimals)
    step6 = re.sub(r"\b\d+(?:\.\d+)?\b", _replace_number, step6)
    record_change("number_expansion", current, step6, "Convert digits and years to words")
    current = step6

    # Stage 7: Acronyms and initialisms
    step7 = current
    # Word-boundary replacements for initialisms
    for acronym, expanded in _INITIALISMS.items():
        pattern = rf"\b{re.escape(acronym)}\b"
        step7 = re.sub(pattern, expanded, step7)

    # Word-boundary replacements for pronounceable acronyms
    for acronym, title_cased in _PRONOUNCEABLE_ACRONYMS.items():
        pattern = rf"\b{re.escape(acronym)}\b"
        step7 = re.sub(pattern, title_cased, step7)

    record_change("acronym_handling", current, step7, "Expand initialisms or normalize acronym case")
    current = step7

    # Stage 8: Punctuation and whitespace cleanup
    step8 = current
    # Remove hyphens that are not between alphanumeric characters
    step8 = re.sub(r"(?<!\w)-(?!\w)", " ", step8)
    # Ensure space after punctuation if followed by word
    step8 = re.sub(r"([.,!?;:])([A-Za-z])", r"\1 \2", step8)
    # Remove spaces before punctuation
    step8 = re.sub(r"\s+([.,!?;:])", r"\1", step8)
    # Collapse multiple spaces
    step8 = re.sub(r"\s+", " ", step8).strip()
    record_change("whitespace_cleanup", current, step8, "Collapse whitespace and normalize punctuation spacing")
    current = step8

    return current, audit


def normalize_text(text: str) -> str:
    """Normalize English text for TTS modeling.

    Args:
        text: Raw transcript string.

    Returns:
        Clean, normalized string.
    """
    normalized, _ = normalize_text_verbose(text)
    return normalized
